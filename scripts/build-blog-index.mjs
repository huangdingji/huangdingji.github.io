import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const blogDirectory = path.join(projectRoot, 'blog');
const outputFile = path.join(projectRoot, 'assets', 'js', 'blog-posts.js');

const categoryRules = [
  {
    id: 'market',
    label: 'Market notes',
    test: /india|market|bis|import-guide/
  },
  {
    id: 'buyer',
    label: 'Buyer channels',
    test: /distributor|supplier|wholesaler|hardware-store|maintenance-repair|sanitary-ware|water-purifier|pipe-fitting/
  },
  {
    id: 'packing',
    label: 'Packing & OEM',
    test: /oem|packaging|carton|sourcing/
  },
  {
    id: 'specification',
    label: 'Specifications',
    test: /12mm|19mm|length|thickness|density|weight|color|specification|temperature|shelf-life/
  },
  {
    id: 'product',
    label: 'Product & use',
    test: /.*/
  }
];

function decodeEntities(value) {
  return value
    .replaceAll('&amp;', '&')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>');
}

function matchContent(html, pattern, fallback = '') {
  return decodeEntities(html.match(pattern)?.[1]?.trim() || fallback);
}

function cleanTitle(title) {
  return title.split('|')[0].trim();
}

const filenames = (await readdir(blogDirectory))
  .filter((filename) => filename.endsWith('.html') && filename !== 'index.html')
  .sort();

const posts = [];

for (const filename of filenames) {
  const html = await readFile(path.join(blogDirectory, filename), 'utf8');
  const slug = filename.replace(/\.html$/, '');
  const rawTitle = matchContent(html, /<title>([^<]+)<\/title>/i, slug.replaceAll('-', ' '));
  const description = matchContent(html, /<meta\s+name="description"\s+content="([^"]*)"/i);
  const published = matchContent(html, /["']datePublished["']\s*:\s*["']([^"']+)["']/i, '2026-01-01');
  const modified = matchContent(html, /["']dateModified["']\s*:\s*["']([^"']+)["']/i, published);
  const category = categoryRules.find((rule) => rule.test.test(slug));

  posts.push({
    slug,
    url: `../blog/${filename}`,
    title: cleanTitle(rawTitle),
    description,
    published,
    modified,
    category: category.id,
    categoryLabel: category.label
  });
}

posts.sort((left, right) => {
  const dateOrder = right.published.localeCompare(left.published);
  return dateOrder || left.title.localeCompare(right.title);
});

const banner = '// Generated by scripts/build-blog-index.mjs. Do not edit by hand.\n';
const output = `${banner}window.BLOG_POSTS = Object.freeze(${JSON.stringify(posts, null, 2)});\n`;

await writeFile(outputFile, output, 'utf8');
console.log(`Generated ${posts.length} blog records at ${path.relative(projectRoot, outputFile)}`);
