import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const blogDirectory = path.join(projectRoot, 'blog');
const outputFile = path.join(projectRoot, 'assets', 'js', 'blog-posts.js');
const hubFile = path.join(blogDirectory, 'index.html');
const categoryOverrides = {
  '19mm-ptfe-tape-supplier': { id: 'specification', label: 'Specifications' },
  'yellow-gas-ptfe-tape-supplier': { id: 'product', label: 'Product & use' },
  'how-to-choose-ptfe-tape-for-wholesale-orders': { id: 'buyer', label: 'Buying guides' }
};
const readingOrder = [
  'how-to-choose-ptfe-tape-for-wholesale-orders', 'ptfe-tape-thickness-guide',
  'oem-ptfe-tape-packaging-guide', 'ptfe-tape-specifications',
  'ptfe-tape-thickness-wholesale', 'ptfe-tape-roll-weight',
  'ptfe-tape-roll-length', 'ptfe-tape-vs-thread-sealant', 'ptfe-tape-carton-packing'
];
const readingPriority = new Map(readingOrder.map((slug, index) => [slug, index]));

const categoryRules = [
  {
    id: 'market',
    label: 'Market notes',
    test: /india|market|bis|import-guide/
  },
  {
    id: 'buyer',
    label: 'Buying guides',
    test: /distributor|supplier|wholesaler|hardware-store|maintenance-repair|sanitary-ware|water-purifier|pipe-fitting/
  },
  {
    id: 'packing',
    label: 'Packing & OEM',
    test: /oem|packaging|carton|sourcing/
  },
  {
    id: 'specification',
    label: 'Specifications',
    test: /12mm|19mm|length|thickness|density|weight|color|specification|temperature|shelf-life/
  },
  {
    id: 'product',
    label: 'Product & use',
    test: /.*/
  }
];

function decodeEntities(value) {
  return value
    .replaceAll('&amp;', '&')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>');
}

function matchContent(html, pattern, fallback = '') {
  return decodeEntities(html.match(pattern)?.[1]?.trim() || fallback);
}

function cleanTitle(title) {
  return title.split('|')[0].trim();
}

const filenames = (await readdir(blogDirectory))
  .filter((filename) => filename.endsWith('.html') && filename !== 'index.html')
  .sort();

const posts = [];

for (const filename of filenames) {
  const html = await readFile(path.join(blogDirectory, filename), 'utf8');
  const slug = filename.replace(/\.html$/, '');
  const rawTitle = matchContent(html, /<title>([^<]+)<\/title>/i, slug.replaceAll('-', ' '));
  const description = matchContent(html, /<meta\s+name="description"\s+content="([^"]*)"/i);
  const published = matchContent(html, /["']datePublished["']\s*:\s*["']([^"']+)["']/i, '2026-01-01');
  const modified = matchContent(html, /["']dateModified["']\s*:\s*["']([^"']+)["']/i, published);
  const category = categoryOverrides[slug] || categoryRules.find((rule) => rule.test.test(slug));

  posts.push({
    slug,
    url: `../blog/${filename}`,
    title: cleanTitle(rawTitle),
    description,
    published,
    modified,
    category: category.id,
    categoryLabel: category.label
  });
}

posts.sort((left, right) => {
  const priorityOrder = (readingPriority.get(left.slug) ?? 999) - (readingPriority.get(right.slug) ?? 999);
  const dateOrder = right.published.localeCompare(left.published);
  return priorityOrder || dateOrder || left.title.localeCompare(right.title);
});

const banner = '// Generated by scripts/build-blog-index.mjs. Do not edit by hand.\n';
const output = `${banner}window.BLOG_POSTS = Object.freeze(${JSON.stringify(posts, null, 2)});\n`;

await writeFile(outputFile, output, 'utf8');
console.log(`Generated ${posts.length} blog records at ${path.relative(projectRoot, outputFile)}`);

// Keep the full library crawlable and useful before JavaScript enhancement.
const escapeHtml = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
const categoryLabels = {
  all: 'All guides', specification: 'Specifications', packing: 'Packing & OEM',
  buyer: 'Buying guides', product: 'Product & use', market: 'Market notes'
};
const filters = Object.entries(categoryLabels).map(([id, label]) => {
  const count = id === 'all' ? posts.length : posts.filter(post => post.category === id).length;
  return `<button type="button" data-category="${id}" aria-pressed="${id === 'all'}" aria-controls="guideResults"><span>${escapeHtml(label)}</span><small>${count}</small></button>`;
}).join('\n');
const cards = posts.map(post => `<article class="blog-card"><p class="blog-card-category">${escapeHtml(post.categoryLabel)}</p><h3><a href="${escapeHtml(post.url)}">${escapeHtml(post.title)}</a></h3><p class="blog-card-description">${escapeHtml(post.description)}</p><a class="blog-card-link" href="${escapeHtml(post.url)}">Read guide <svg aria-hidden="true" class="arrow-icon" viewBox="0 0 20 20"><path d="M3 10h13m-5-5 5 5-5 5"></path></svg></a></article>`).join('\n');
const schema = {
  '@context': 'https://schema.org', '@type': 'CollectionPage',
  '@id': 'https://www.qzjy.store/blog/#library', url: 'https://www.qzjy.store/blog/',
  name: 'PTFE Tape Blog | Practical Buyer Guides',
  publisher: { '@id': 'https://www.qzjy.store/#organization' },
  mainEntity: {
    '@type': 'ItemList', numberOfItems: posts.length,
    itemListElement: posts.map((post, i) => ({ '@type': 'ListItem', position: i + 1, name: post.title, url: new URL(post.url, 'https://www.qzjy.store/blog/').href }))
  }
};
let hub = await readFile(hubFile, 'utf8');
for (const [marker, content] of [['BLOG_FILTERS', filters], ['BLOG_CARDS', cards]]) {
  const region = new RegExp(`<!-- ${marker}_START -->[\\s\\S]*?<!-- ${marker}_END -->`);
  if (!region.test(hub)) throw new Error(`Missing ${marker} markers in blog/index.html`);
  hub = hub.replace(region, `<!-- ${marker}_START -->\n${content}\n<!-- ${marker}_END -->`);
}
hub = hub.replace(/(<span data-guide-total>)[^<]*(<\/span>)/, (_, before, after) => `${before}${posts.length}${after}`);
hub = hub.replace(/(<p data-blog-status[^>]*>)[^<]*(<\/p>)/, (_, before, after) => `${before}${posts.length} guides${after}`);
hub = hub.replace(/(<script type="application\/ld\+json" data-blog-schema>)[\s\S]*?(<\/script>)/, (_, before, after) => `${before}${JSON.stringify(schema, null, 2)}${after}`);
await writeFile(hubFile, hub, 'utf8');
console.log(`Updated the static library, category counts and collection metadata in blog/index.html`);
